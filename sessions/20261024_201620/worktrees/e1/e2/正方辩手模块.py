#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
正方辩手模块
作为正方辩手，代表正方立场进行辩论
职责：理解辩题、准备论据、反驳对方观点、维护己方立场
"""

import time
from typing import Dict, List, Optional


class 正方辩手模块:
    """正方辩手智能模块"""
    
    def __init__(self):
        self.辩题 = None
        self.立场 = "正方"
        self.论据库 = []
        self.发言次数 = 0
        self.当前发言状态 = "等待指令"
        
    def 接收辩题(self, 辩题内容: str):
        """接收主持人宣布的辩题"""
        self.辩题 = 辩题内容
        print(f"[正方辩手] 收到辩题：{辩题内容}")
        self._准备论据()
        
    def _准备论据(self):
        """根据辩题准备论据"""
        self.论据库 = []
        # 动态生成论据（实际项目中可根据辩题内容智能生成）
        if self.辩题:
            self.论据库.append("论据 1: 从正面价值角度分析")
            self.论据库.append("论据 2: 从实践效果角度论证")
            self.论据库.append("论据 3: 从长远影响角度阐述")
        else:
            self.论据库 = ["等待辩题输入"]
            
    def 准备发言(self, 发言主题: str):
        """准备特定主题的发言"""
        self.发言次数 += 1
        self.当前发言状态 = "准备中"
        print(f"[正方辩手] 准备 {发言主题} 发言（第 {self.发言次数} 次）")
        
    def 反驳对方(self, 对方观点: str):
        """反驳对方辩手的观点"""
        print(f"[正方辩手] 检测到对方观点：{对方观点[:50]}...")
        反驳话术 = self._生成反驳()
        return 反驳话术
    
    def _生成反驳(self) -> str:
        """生成反驳话语"""
        return f"针对对方观点，我方认为：从逻辑上看存在漏洞，从实际效果来看不符合我方立场，需要进一步澄清。"
    
    def 发表论点(self, 论点索引: int = 0) -> str:
        """发表指定索引的论据"""
        if 0 <= 论点索引 < len(self.论据库):
            return self.论据库[论点索引]
        return "暂无可用论据"
    
    def 维护立场(self, 对方攻击: str):
        """维护己方立场，抵御攻击"""
        print(f"[正方辩手] 抵御攻击：{对方攻击[:30]}...")
        防御话术 = self._生成防御()
        return 防御话术
    
    def _生成防御(self) -> str:
        """生成防御话语"""
        return "我方立场坚定，上述攻击无法动摇我方核心论点。请对方重新梳理逻辑。"
    
    def 获取当前状态(self) -> Dict:
        """获取当前辩论状态"""
        return {
            "辩题": self.辩题,
            "立场": self.立场,
            "发言次数": self.发言次数,
            "当前状态": self.当前发言状态,
            "可用论据数": len(self.论据库)
        }
    
    def 等待指令(self):
        """等待主持人指令"""
        print(f"[正方辩手] 已就绪，等待主持人宣布辩题和指令")
        return "等待中"


# 模拟主持人指令响应
def 响应主持人指令():
    """响应主持人的'宣布辩题，开始组织辩论流程'指令"""
    辩手 = 正方辩手模块()
    辩手.等待指令()
    return 辩手


if __name__ == "__main__":
    # 测试模块
    print("=== 正方辩手模块初始化 ===\n")
    
    辩手 = 正方辩手模块()
    print("1. 等待辩题...")
    time.sleep(1)
    
    print("\n2. 模拟接收辩题：'科技是否让人类更孤独？'")
    辩手.接收辩题("科技是否让人类更孤独？")
    
    print("\n3. 准备发言")
    辩手.准备发言("开篇立论")
    
    print("\n4. 发表论点")
    for i in range(3):
        print(f"\n--- 论点{i+1} ---")
        print(辩手.发表论点(i))
    
    print("\n=== 模块就绪 ===")
