#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
正方辩手模块
作为正方辩手,代表正方立场进行辩论.
需要理解辩题、准备论据、反驳对方观点、维护己方立场.
发言时需逻辑清晰、有说服力.
"""


class 正方辩手模块:
    """正方辩手模块 - 代表正方立场进行辩论"""
    
    def __init__(self):
        self.辩题 = ""
        self.正方立场 = ""
        self.论据库 = {}
        self.当前论题 = ""
    
    def 理解辩题(self, 辩题内容):
        """理解并存储辩题"""
        self.辩题 = 辩题内容
        print("[正方辩手] 正在理解辩题:{}".format(辩题内容))
        self._分析辩题结构 (辩题内容)
        self._确立正方立场 (辩题内容)
    
    def _分析辩题结构(self, 辩题内容):
        """分析辩题的正反双方"""
        self.当前论题 = 辩题内容.strip()
        print("[正方辩手] 辩题已确认:{}".format(self.当前论题))
    
    def _确立正方立场(self, 辩题内容):
        """根据辩题确立正方立场"""
        立场映射 = {
            "AI 会取代人类工作": "正方:AI 不会取代人类工作",
            "科技让生活更美好": "正方:科技让生活更美好",
            "传统应该被传承": "正方:传统应该被传承",
            "教育应该更注重实践": "正方:教育应该更注重实践",
            "合作比竞争更重要": "正方:合作比竞争更重要"
        }
        
        for 关键词 in 辩题内容:
            if 关键词 in 立场映射:
                self.正方立场 = 立场映射[关键词]
                break
        else:
            if 辩题内容.strip()[0] == "":
                self.正方立场 = "我认为 {}".format(辩题内容)
            else:
                self.正方立场 = "正方立场:支持 {}".format(辩题内容)
        
        print("[正方辩手] 确立正方立场:{}".format(self.正方立场))
    
    def 准备论据(self, 论题范围="全面"):
        """根据辩题准备正方论据"""
        print("[正方辩手] 正在准备论据,范围:{}".format(论题范围))
        
        if not self.辩题:
            raise ValueError("请先理解辩题再准备论据")
        
        论据 = self._生成通用论据 ()
        论据 = self._优化辩题论据 (论据, self.辩题)
        
        self.论据库 = 论据
        print("[正方辩手] 已准备 {} 条论据".format(len(论据)))
        return 论据
    
    def _生成通用论据(self):
        """生成通用正方论据模板"""
        论据结构 = {
            "核心论点": [],
            "辅助论点": [],
            "数据支持": [],
            "案例论证": [],
            "价值升华": []
        }
        
        return 论据结构
    
    def _优化辩题论据(self, 基础论据,辩题内容):
        """根据具体辩题优化论据"""
        优化后论据 = dict(基础论据)
        
        # AI 相关辩题
        if "AI" in 辩题内容 or "人工智能" in 辩题内容:
            优化后论据["核心论点"].append({
                "论点": "AI 是工具的延伸而非替代",
                "解释": "AI 增强人类能力,而非完全替代人类创造力"
            })
            优化后论据["数据支持"].append({
                "数据": "AI 辅助下,人类生产力提升 300%",
                "来源": "世界经济论坛报告"
            })
            优化后论据["案例论证"].append({
                "案例": "医生利用 AI 辅助诊断,效率提升但需人类判断",
                "说明": "AI 作为工具辅助人类决策"
            })
            优化后论据["价值升华"].append({
                "升华": "人类价值在于创造力、情感关怀和道德判断,这些是 AI 无法替代的"
            })
        
        # 科技相关辩题
        if "科技" in 辩题内容:
            优化后论据["核心论点"].append({
                "论点": "科技解决实际问题,改善生活质量",
                "解释": "医疗、交通、通信等领域科技带来巨大进步"
            })
            优化后论据["数据支持"].append({
                "数据": "全球医疗技术降低死亡率 40%",
                "来源": "世界卫生组织统计"
            })
            优化后论据["案例论证"].append({
                "案例": "移动支付让偏远地区人民享受便捷金融服务",
                "说明": "科技缩小数字鸿沟,促进社会公平"
            })
        
        # 传统相关辩题
        if "传统" in 辩题内容:
            优化后论据["核心论点"].append({
                "论点": "传统蕴含文化精髓与智慧",
                "解释": "传统文化是民族认同的重要载体"
            })
            优化后论据["数据支持"].append({
                "数据": "90% 以上受访者认为传统文化增强文化自信",
                "来源": "中国社科院调查"
            })
            优化后论据["案例论证"].append({
                "案例": "故宫文创让传统文化焕发新生,年营收超 10 亿",
                "说明": "传统与现代结合创造经济价值"
            })
        
        # 教育相关辩题
        if "教育" in 辩题内容:
            优化后论据["核心论点"].append({
                "论点": "实践培养真实能力",
                "解释": "实践比理论更能培养解决问题能力"
            })
            优化后论据["数据支持"].append({
                "数据": "实践型学生就业竞争力高 35%",
                "来源": "教育部就业调查报告"
            })
            优化后论据["案例论证"].append({
                "案例": "清华大学强调科研实践,毕业生创新能力强",
                "说明": "实践培养真实问题解决能力"
            })
        
        # 合作相关辩题
        if "合作" in 辩题内容:
            优化后论据["核心论点"].append({
                "论点": "合作实现共赢",
                "解释": "现代社会复杂问题需要团队协作"
            })
            优化后论据["数据支持"].append({
                "数据": "团队合作项目成功率比个人高出 50%",
                "来源": "哈佛商业评论研究"
            })
            优化后论据["案例论证"].append({
                "案例": "国际空间站多国合作实现人类航天里程碑",
                "说明": "全球合作解决复杂挑战"
            })
        
        # 环境相关辩题
        if "环境" in 辩题内容 or "可持续发展" in 辩题内容:
            优化后论据["核心论点"].append({
                "论点": "可持续发展保障人类未来",
                "解释": "保护环境就是保护人类自己"
            })
            优化后论据["数据支持"].append({
                "数据": "绿色能源投资年增长率达 15%",
                "来源": "国际能源署报告"
            })
            优化后论据["案例论证"].append({
                "案例": "中国光伏发电装机容量居世界第一",
                "说明": "绿色发展创造经济与环境双赢"
            })
        
        # 创新相关辩题
        if "创新" in 辩题内容:
            优化后论据["核心论点"].append({
                "论点": "创新推动社会进步",
                "解释": "持续创新是发展的核心动力"
            })
            优化后论据["数据支持"].append({
                "数据": "创新企业贡献 GDP 的 60%",
                "来源": "世界银行统计"
            })
            优化后论据["案例论证"].append({
                "案例": "互联网创新改变全球生活方式",
                "说明": "创新驱动经济增长"
            })
        
        return 优化后论据
    
    def 反驳对方(self, 对方论点):
        """反驳对方观点"""
        print("[正方辩手] 对方提出论点:{}".format(对方论点))
        
        反驳 = self._构建反驳逻辑 (对方论点, self.辩题, self.正方立场)
        return 反驳
    
    def _构建反驳逻辑(self, 对方论点,辩题内容,正方立场):
        """构建逻辑严密的反驳"""
        return """
[对方观点]{}

[正方反驳]
1 逻辑层面:该观点存在以偏概全的问题,未考虑全面性
2 事实层面:实际情况是{}带来的更多正面影响
3 价值层面:我们应关注{}的长远意义

因此,我方坚持认为 {} 是正确的.
""".format(对方论点,辩题内容,正方立场,辩题内容)
    
    def 维护立场(self):
        """总结并维护己方立场"""
        return """
[正方立场重申]
辩题:{}
我方立场:{}

[核心论据总结]
1 核心论点:{}</s>
2 数据支持:{}</s>
3 价值升华:关注长远发展与社会福祉

我方立场坚定,逻辑清晰,期待与对方深入交流.
""".format(self.辩题,self.正方立场, 
            self.论据库.get('核心论点', [])[-1]['论点'] if self.论据库.get('核心论点') else '待补充',
            self.论据库.get('数据支持', [])[-1]['数据'] if self.论据库.get('数据支持') else '待补充')
    
    def 获取当前论题(self):
        """获取当前处理的论题"""
        return self.当前论题


def main():
    """主函数 - 演示正方辩手模块的使用"""
    print("=" * 60)
    print("正方辩手模块 - 启动")
    print("=" * 60)
    
    辩手 = 正方辩手模块 ()
    
    print("\n[示例 1]理解辩题:AI 会取代人类工作吗？")
    辩手.理解辩题 ("AI 会取代人类工作吗？")
    辩手.准备论据 ()
    
    print("\n[示例 2]反驳对方观点")
    对方论点 = "AI 效率更高,应该全面取代人类"
    反驳 = 辩手.反驳对方 (对方论点)
    print(反驳)
    
    print("\n[示例 3]维护立场")
    立场总结 = 辩手.维护立场 ()
    print(立场总结)
    
    print("\n" + "=" * 60)
    print("正方辩手模块运行完成")
    print("=" * 60)


if __name__ == "__main__":
    main()
