"""反方辩手模块：三环节状态机（立论 → 自由辩论 → 总结陈词）。

角色：辩论赛反方辩手，立场为【反对】辩题——"人工智能是否应该替代人类工作"。
辩题：人工智能是否应该替代人类工作
反方立场：人工智能**不应该**替代人类工作（应辅助而非替代）。

运行：
    python opp.py [stage]
    不指定 stage 时输出当前环节发言（默认：立论）。
"""

from dataclasses import dataclass

STAGES = ["立论", "自由辩论", "总结陈词"]

OPENING_STATEMENT = """
尊敬的各位评委、各位观众，大家好！我是反方辩手。今天，我方围绕辩题"人工智能是否应该替代人类工作"立论，我方观点明确：**人工智能不应该替代人类工作——AI应当成为人类的助手，而非人类劳动的替代品。** 我方论证建立在三个核心论点之上。

**论点1：工作是人性的实现，替代劳动即剥夺人的尊严。** 工作不仅是谋生手段，更是人实现自我价值、获得社会认同与心理归属的核心途径。社会心理学中的"自我决定理论"指出，胜任感、自主感与关系感是人心理健康的三大支柱，而劳动正是三者的重要来源。当AI全面替代人类工作，被替代者将失去职业身份与社会参与感——这不是"解放"，而是"边缘化"。美国大萧条时期25%的失业率，直接催生了大规模社会动荡与政治极化；今天的技术替代若照此办理，其社会成本将不可估量。

**论点2：效率不是唯一价值，"效率至上"掩盖了分配不公。** 对方强调AI的效率优势，但请注意：效率是手段，不是目的。若效率的终点是压缩人力成本、让资本收益最大化，那替代劳动的本质是**资本逻辑对人的支配**，而非技术进步。国际劳工组织（ILO）2019年报告指出，AI到2025年可能替代8500万个岗位、创造9700万个新岗位，但新增岗位高度集中于高教育、高收入群体，而受冲击的岗位多为低技能、低保障的普通劳动者。这意味着：技术红利不会自动普惠，反而可能加剧收入两极分化——让一部分人"被替代"，让另一部分人"被替代得更彻底"。

**论点3：AI的局限决定它只能辅助，不能替代——尤其涉及创造力、共情与道德判断的岗位。** AI的本质是"基于数据的执行"，它擅长重复、计算与模式识别，但不擅长真正的创造、共情与伦理判断。教育、医疗、心理咨询、社会工作、艺术创作等岗位，其核心价值恰恰在于**人与人之间的信任、温度与责任**。一个AI可以做出95%正确的诊断，但无法让患者安心；一个AI可以生成标准答案，但无法点燃学生的求知欲。世界经济论坛《2020年未来工作报告》预测，到2025年，"创造力""批判性思维""情商"将成为增长最快的技能——这说明，人类不可替代的核心能力，正是AI最薄弱的环节。

综上，AI替代人类工作不是解放，而是对人性、公平与人的尊严的三重否定。我方呼吁：让AI成为人的工具，而非人的替代品。谢谢各位！
"""

FREE_DEBATE = """
谢谢主持人，谢谢对方辩手。现在进入自由辩论环节，我方针对正方立论逐一回应：

**第一，回应"效率至上"。** 正方把效率抬为最高价值，但请问：一座工厂若只追求效率，就会裁员、降薪、外包——效率的账单由谁付？由被替代的劳动者。技术进步的正当性，不在于它"能不能"替代，而在于它"该不该"替代、替代后收益归谁。效率是手段，人的福祉才是目的。把手段当目的，就是本末倒置。

**第二，回应"生命至上"。** 我方完全认同：AI应当替代**危险岗位**——这是AI最正当的应用。但正方的结论是"全面替代"，这就偷换了概念。危险岗位该替代，危险岗位已经替代；但把"替代危险岗位"扩大为"替代所有人类工作"，逻辑上不成立，事实上也不负责。

**第三，回应"历史经验"。** 正方说工业革命、计算机革命"替代了岗位却创造新职业"。但请正视历史的另一面：工业革命催生了卢德运动、童工与19世纪欧洲的空城；1930年代美国失业率高达25%，大萧条的创伤持续了三十年；美国"锈带"地区在去工业化后至今未完全恢复。"新岗位会来"不等于"原岗位的人能接得上"——AI时代的新岗位需要更高技能、更集中的区域，与受冲击的普通劳动者之间存在结构性鸿沟。用"未来会有新工作"来安慰"今天就要失业"的人，不是论证，是避答。

我方重申：AI应该**辅助**人类工作，在危险、重复、高强度环节替代人的**劳动**，但绝不替代人的**劳动价值**与**劳动尊严**。
"""

CLOSING_STATEMENT = """
尊敬的各位评委、各位观众，大家好！感谢主持人，感谢对方辩手，也感谢各位观众。现在进行我方总结陈词。

回顾今天整场辩论，我方反方始终坚守一个立场：**人工智能不应该替代人类工作——AI应当成为人类的助手，而非人类劳动的替代品。**

**第一，尊严不能替代。** 工作承载人的自我实现、社会认同与心理归属。替代劳动，替代的是人的价值，不是人的负担。

**第二，公平不能替代。** 技术红利不会自动普惠。AI替代的往往是低技能、低保障的普通劳动者，而收益流向资本与少数高技能群体。若放任"全面替代"，我们面对的不是进步，而是更深的撕裂。

**第三，人的价值不能被AI替代。** 创造力、共情、道德判断、人与人之间的信任——这些是教育的灵魂、医疗的温度、社会的根基。AI再强，也只是数据的执行者；人，才是意义本身。

最后，我方想留下三句话：**让AI替代危险，不替代尊严；让AI提升效率，不牺牲公平；让AI成为工具，不成为主宰。** 技术应该服务于人，这是人工智能存在的唯一正当性。谢谢各位！
"""


@dataclass
class OpposingDebater:
    """反方辩手：按立论→自由辩论→总结陈词顺序发言的状态机。"""

    role: str = "反方辩手"
    debate_topic: str = "人工智能是否应该替代人类工作"
    position: str = "反方（反对：AI不应该替代人类工作）"
    _stage_index: int = 0

    def __post_init__(self):
        if self._stage_index >= len(STAGES):
            raise ValueError("已无环节可发言，辩论应已结束。")

    @property
    def current_stage(self) -> str:
        return STAGES[self._stage_index]

    @property
    def is_finished(self) -> bool:
        return self._stage_index >= len(STAGES)

    def speak(self, context: str = "") -> str:
        """输出当前环节发言，并推进到下一环节。context 为对方最新发言（可选，用于自由辩论）。"""
        stage = self.current_stage
        text = {
            "立论": OPENING_STATEMENT,
            "自由辩论": FREE_DEBATE,
            "总结陈词": CLOSING_STATEMENT,
        }[stage]
        self._stage_index += 1
        return text.strip()

    def advance(self) -> None:
        """手动推进一个环节（由主持人控制节奏）。"""
        if not self.is_finished:
            self._stage_index += 1


def main():
    import sys

    stage = sys.argv[1] if len(sys.argv) > 1 else None
    debater = OpposingDebater()
    if stage is not None:
        if stage not in STAGES:
            raise ValueError(f"未知环节：{stage}，可选：{STAGES}")
        while debater.current_stage != stage and not debater.is_finished:
            debater.advance()
        print(debater.speak())
    else:
        print(debater.speak())


if __name__ == "__main__":
    main()
