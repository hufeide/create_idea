#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""正方辩手模块：一场辩论赛（正方：人工智能应该替代人类工作）

职责：在主持人引导下按顺序发言——立论（2-3个核心论点+具体论据）、
自由辩论（反驳对方、强化己方）、总结陈词。逻辑严密、语言有力、紧扣辩题。
每次只输出一段自己的发言，等待主持人或对方辩手回复后再继续。
"""

TOPIC = "人工智能是否应该替代人类工作"
AFF_POS = "人工智能应该替代人类工作"

# 核心论点（立论用）
CORE_POINTS = [
    {
        "title": "效率至上：AI在重复性与高精度劳动中全面超越人类",
        "evidence": (
            "在制造业，AI驱动的自动化产线可实现7×24小时不间断运行，"
            "效率提升数倍。以特斯拉的'Optimus'人形机器人和汽车工厂"
            "焊接、喷涂环节为例，机器人作业精度稳定在微米级，"
            "而人类因疲劳、情绪波动导致差错率随工时上升。"
            "2023年麦肯锡报告显示，AI与自动化每年可为全球制造业"
            "创造约1.5万亿美元的效率增益。"
        ),
    },
    {
        "title": "生命至上：危险岗位必须交给AI，这是文明的进步",
        "evidence": (
            "采矿、深海勘探、核废料处理、灾害救援等岗位每年造成大量"
            "人员伤亡。中国煤矿百万吨原煤死亡人数虽持续下降，"
            "但2023年全国工矿事故中仍有人员伤亡。AI驱动的无人矿车、"
            "深海探测机器人（如'蛟龙号'）已实现危险环境的无人化作业，"
            "让'人'从'危险中解放'，是替代的正当性所在。"
        ),
    },
    {
        "title": "历史经验：技术替代不消灭就业，而是重构就业",
        "evidence": (
            "工业革命取代了手工业者，却催生了纺织厂、铁路、钢铁等"
            "新职业，总就业率上升；计算机革命淘汰了大量文职工作，"
            "却创造了程序员、数据分析师、互联网运营等数以亿计的新岗位。"
            "麦肯锡2023年报告预测，到2030年，AI将替代约3亿个岗位，"
            "同时创造4.8亿个新岗位。AI替代的是'任务'，"
            "不是'人的价值'。"
        ),
    },
]


class AffirmativeDebater:
    """正方辩手：维护发言阶段状态，每次推进只输出一段发言。"""

    def __init__(self, topic: str = TOPIC):
        self.topic = topic
        self.stage = 0  # 0=未发言；1=已立论；2=已自由辩论；3=已总结

    # ---------- 环节一：立论 ----------
    def opening_argument(self) -> str:
        """立论：提出核心论点与具体论据。"""
        self.stage = 1
        parts = [
            f"尊敬的各位评委、各位观众，大家好！我是正方辩手。"
            f"今天，我方围绕辩题“{self.topic}”立论，"
            f"我方观点明确：人工智能应该替代人类工作。"
            "我方论证建立在三个核心论点之上。",
        ]
        for i, point in enumerate(CORE_POINTS, 1):
            parts.append(f"论点{i}：{point['title']}。{point['evidence']}")
        parts.append(
            "综上，AI替代人类工作不是对人类的否定，而是对人类力量的"
            "解放与升华。谢谢各位！"
        )
        return "\n\n".join(parts)

    # ---------- 环节二：自由辩论 ----------
    def free_debate(self, opponent: str = "") -> str:
        """自由辩论：针对反方观点进行反驳与己方强化。"""
        self.stage = 2
        return (
            "感谢反方辩手的精彩发言。我方从三个层面回应反方。\n\n"
            "其一，反方以‘AI缺乏创造力与情感’为由反对替代，"
            "这是对辩题的偷换。辩题讨论的是‘是否应该替代’，"
            "不是‘AI能否替代所有工作’。替代是分工问题，不是能力问题——"
            "算盘不能替代数学家，但这不阻止算盘替代手写计算。\n\n"
            "其二，反方担忧‘失业浪潮’，但历史已经给出答案："
            "每次技术革命都先创造新岗位、再消化旧岗位。"
            "从蒸汽机到计算机，总就业率从未因自动化而下降。"
            "真正的问题不是‘AI会不会替代工作’，"
            "而是‘我们是否及时做好再培训与社会保障’——"
            "这是治理问题，不是反对替代的理由。\n\n"
            "其三，反方强调‘人的尊严’，但我方认为，"
            "让1亿矿工免于塌方、让1亿工人免于重复劳动的疲劳与伤病，"
            "才是对人的尊严的真正尊重。解放人，比束缚人更值得骄傲。\n\n"
            "我方再次重申：人工智能应该替代人类工作，"
            "这是效率、安全与文明进步的共同选择。"
        )

    # ---------- 环节三：总结陈词 ----------
    def closing(self) -> str:
        """总结陈词：收束全篇，升华立场。"""
        self.stage = 3
        return (
            "感谢反方辩手全程的交锋。我方总结陈词如下。\n\n"
            "今天，我方用三个论据回答了‘为什么应该替代’："
            f"第一，在效率上，AI以微米级精度和全天候运转"
            f"超越了人类重复劳动的极限；第二，在安全上，AI把人类"
            f"从危险岗位上解放出来，这是文明的进步而非退步；"
            "第三，在历史维度上，每一次技术替代都重构而非消灭就业，"
            "AI时代的新岗位将远超被替代的旧岗位。\n\n"
            "反方担忧失业、担忧情感缺失、担忧人的价值被稀释，"
            "这些担忧值得重视，但都不构成‘不应该替代’的理由——"
            "就像我们担忧汽车替代马车，却从未因此拒绝汽车。\n\n"
            "我们站在技术的浪潮前，不是站在人类的对立面。"
            "让AI去做机器擅长的事，让人去做人擅长的事——"
            f"这正是对辩题“{self.topic}”最有力、最负责任的答案："
            f"人工智能应该替代人类工作，因为替代的是任务，"
            "解放的是人，升华的是文明。\n\n"
            "我方陈述完毕，谢谢各位！"
        )

    # ---------- 统一入口 ----------
    def speak(self, action: str, **kwargs) -> str:
        """统一入口：action ∈ {opening, free, closing}。"""
        if action == "opening":
            return self.opening_argument()
        if action == "free":
            return self.free_debate(**kwargs)
        if action == "closing":
            return self.closing()
        raise ValueError(f"未知发言环节: {action}")


if __name__ == "__main__":
    debater = AffirmativeDebater()
    print("=== 正方立论 ===")
    print(debater.opening_argument())
    print("\n\n=== 自由辩论（示例）===")
    print(debater.free_debate())
    print("\n\n=== 总结陈词（示例）===")
    print(debater.closing())
