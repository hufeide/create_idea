#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""主持人模块：一场辩论赛（2名辩手 + 1名主持人）

职责：开场宣布辩题、介绍双方辩手、说明流程，
控制发言顺序与节奏（正方立论→反方立论→自由辩论→总结陈词），
最后交由裁判评判。每次只输出一段主持人发言。

流程状态（step）：
  1  待正方立论          2  待反方立论
  3  自由辩论中（free_turn：0=正方待发言，1=反方待发言）
  4  待正方总结  5  待反方总结
  6  辩论结束，交由裁判
"""

TOPIC = "人工智能是否应该替代人类工作"
AFF_POS = "人工智能应该替代人类工作"
CON_POS = "人工智能不应该替代人类工作"
AFF = "正方辩手"
CON = "反方辩手"


class Moderator:
    """主持人：维护辩论流程状态，每次推进只输出一段发言。"""

    def __init__(self, topic: str = TOPIC):
        self.topic = topic
        self.step = 0  # 0=未开始
        self.free_turn = 0  # 自由辩论中：0=正方待发言，1=反方待发言

    def opening(self) -> str:
        """开场：宣布辩题、介绍辩手、说明流程，点名正方立论。"""
        self.step = 1
        return (
            "尊敬的各位评委、各位观众，大家晚上好！我是本场辩论赛的主持人。"
            f"今天，我们将围绕一个炙手可热的争议话题——“{self.topic}”——"
            "展开一场精彩的思想交锋！\n\n"
            f"首先，请允许我介绍两位辩手：{AFF}，将为我们阐述"
            f"“{AFF_POS}”的观点；{CON}，将为我们阐述"
            f"“{CON_POS}”的观点。\n\n"
            "今天的辩论流程如下：第一步，正方立论；第二步，反方立论；"
            "第三步，自由辩论，正反双方自由交锋；第四步，总结陈词。"
            "最后，我们将把评判权交给裁判，由裁判作出评判。\n\n"
            f"那么，辩论现在正式开始！首先，有请{AFF}，进行立论。"
        )

    def advance(self) -> str:
        """辩手发言结束后调用：推进流程，输出下一段主持人发言。"""
        if self.step == 1:  # 正方立论完毕
            self.step = 2
            return f"感谢{AFF}精彩的立论。接下来，有请{CON}进行立论。"
        if self.step == 2:  # 反方立论完毕 → 自由辩论
            self.step = 3
            self.free_turn = 0
            return (
                "感谢两位辩手精彩的立论，双方观点已经充分展开，"
                "碰撞的火花已经点燃！\n\n"
                "简要串场点评：正方主张‘AI应该替代人类工作’，"
                "以效率提升、危险岗位替代和历史经验为三大支柱，"
                "强调AI解放的是人的价值而非否定人；"
                "反方则主张‘AI不应替代人类工作’，"
                "从人的尊严、分配公平与AI能力局限出发，"
                "指出效率至上掩盖了分配不公，人的创造力、共情与道德判断"
                "正是AI最薄弱的环节。双方针锋相对，各有锋芒。\n\n"
                "现在进入自由辩论环节。规则如下：正反双方轮流发言，"
                "围绕对方论点进行反驳、强化己方，紧扣辩题、紧扣对方发言，"
                "不得偏离主题，不得人身攻击。"
                f"那么，自由辩论正式开始！首先，有请{AFF}发言。"
            )
        if self.step == 3:  # 自由辩论中：正反轮流
            if self.free_turn == 0:
                self.free_turn = 1
                return f"感谢{AFF}精彩的发言。接下来，有请{CON}回应。"
            else:
                self.free_turn = 0
                return f"感谢{CON}精彩的发言。接下来，有请{AFF}回应。"
        if self.step == 4:  # 正方总结完毕
            self.step = 5
            return (f"感谢{AFF}精彩的总结陈词。最后，有请{CON}"
                    "进行总结陈词。")
        if self.step == 5:  # 反方总结完毕 → 辩论结束
            self.step = 6
            return (
                "感谢两位辩手精彩的总结陈词，也感谢各位评委与观众全程"
                "关注。辩论至此全部结束！接下来，我们将把评判权交给裁判，"
                "请裁判作出评判。"
            )
        return "辩论已经结束，请裁判作出评判。"

    def end_free_debate(self) -> str:
        """自由辩论结束后（由主持人判断时机）调用：转场进入总结陈词。"""
        self.step = 4
        return (
            f"感谢双方精彩的自由辩论，交锋激烈、火花四溅！现在进入"
            f"总结陈词环节，有请{AFF}进行总结陈词。"
        )


if __name__ == "__main__":
    host = Moderator()
    print(host.opening())
