# -*- coding: utf-8 -*-
"""
辩论赛主持人模块（主持人）

职责：
1）宣布辩题并说明辩论规则；
2）引导发言顺序（正方发言→反方发言→驳论→总结陈词）；
3）控制节奏，保持中立公正，不发表任何立场，只负责推进流程，
   并在结束时宣布进入评委评分环节。
"""

# ---------------- 辩题设定 ----------------
DEBATE_TOPIC = "社交媒体平台是否应为用户言论负责"
AFFIRMATIVE = "社交媒体平台应当为用户言论负责"
OPPOSITION = "社交媒体平台不应当为用户言论负责"

# ---------------- 发言顺序 ----------------
SPEAKING_ORDER = [
    ("第一回合", "正方发言", "正方陈述"),
    ("第二回合", "反方发言", "反方陈述"),
    ("第三回合", "驳论", "正反双方依次反驳对方观点"),
    ("第四回合", "总结陈词", "正反双方各作总结陈述"),
]

# ---------------- 辩论规则 ----------------
RULES = [
    "1. 双方按既定顺序发言，不得越序、不得打断对方发言。",
    "2. 每回合发言应紧扣辩题，围绕自身立场陈述论点、证据与理由。",
    "3. 驳论回合只针对对方论点进行反驳，不得偏离辩题。",
    "4. 发言应文明理性，不得人身攻击、辱骂或散播不实信息。",
    "5. 主持人全程保持中立公正，不持任何立场，只负责推进流程与控场。",
    "6. 总结陈词结束后，辩论正式结束，进入评委评分环节。",
]


def build_announcement():
    """生成主持人开场宣布全文（中立公正，不发表立场）。"""
    lines = [
        "各位评委、双方辩手，大家好。我是本场辩论赛的主持人。",
        "",
        f"本场辩论的辩题为：{DEBATE_TOPIC}",
        "",
        f"【正方立场】{AFFIRMATIVE}",
        f"【反方立场】{OPPOSITION}",
        "",
        "请双方辩手确认以上立场表述无误。",
        "",
        "本场辩论的规则与发言顺序如下：",
        "规则：",
        "  " + "\n  ".join(RULES),
        "",
        "发言顺序：",
    ]
    for (round_no, stage, desc) in SPEAKING_ORDER:
        lines.append(f"  {round_no}：{stage}（{desc}）")
    lines.extend([
        "",
        "现在，辩论正式开始。",
        "有请正方发言——",
    ])
    return "\n".join(lines)


def next_stage(current_index):
    """推进到下一个发言环节（仅控场，不评价内容）。"""
    if current_index >= len(SPEAKING_ORDER):
        return "辩论已进行完毕。感谢双方辩手的精彩发言。现在宣布：进入评委评分环节。"
    round_no, stage, desc = SPEAKING_ORDER[current_index]
    return f"好，{round_no}，{stage}现在开始。{desc}，有请。"


def main():
    print(build_announcement())
    print()
    # 演示控场推进（实际由流程驱动调用 next_stage）
    print("【控场提示】")
    print(next_stage(0))


if __name__ == "__main__":
    main()
