#!/usr/bin/env python3
"""组合蛋#5：三个诗意模块的整合实现。

- 模块一（自然意象）：秋风、落叶、月光；语言凝练，意境清冷。
- 模块二（人情温度）：亲情；饭桌、灯光、旧物；语言温暖。
- 模块三（时间哲思）：时间与存在；节奏沉稳，结尾留有余味。

integrate() 负责协调三个模块，输出整合后的诗歌正文。
"""

POEM_ONE = """秋风从远山后面回来
把松针吹成细碎的白
落叶贴着石阶走
走得不急，也不回头
月光落在井水里
井水把它按成一枚硬币
没有人去捡
霜替谁扣了门
远处，灯只亮了一下
夜里，屋檐滴水
滴到旧年
滴到下一年的第一声蝉"""

POEM_TWO = """母亲把灯拧低了一格
怕光刺进你眼睛
汤在碗里响，像谁在门外敲
父亲把咸菜翻一翻
翻到最软的那块
你咬一口
他笑，说，咸
桌上的旧茶壶
泡了三天的水
也泡出了甜味
灯下，他的白发
比盐还白"""

POEM_THREE = """时间在旧钟里走
走得不急
我们以为自己在赶路
其实路一直在走
手边的杯子
从新到旧
旧的，盛过最烫的茶
也盛过最凉的水
存在只是
一次又一次的盛
钟敲完
人还在"""


def poem_one() -> str:
    """模块一：自然意象（秋风、落叶、月光），清冷。"""
    return POEM_ONE


def poem_two() -> str:
    """模块二：人情温度（亲情，饭桌、灯光、旧物），温暖。"""
    return POEM_TWO


def poem_three() -> str:
    """模块三：时间哲思（时间与存在），节奏沉稳，余味收尾。"""
    return POEM_THREE


def integrate() -> str:
    """协调三个模块：清冷—温暖—余味，三段递进，只输出诗歌正文。"""
    return "\n\n\n".join([poem_one(), poem_two(), poem_three()])


if __name__ == "__main__":
    text = integrate()
    print(text)
    with open("poems.txt", "w", encoding="utf-8") as f:
        f.write(text + "\n")
