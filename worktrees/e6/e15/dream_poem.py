#!/usr/bin/env python3
"""
梦想诗篇 - 关于梦想的短诗
充满希望与力量
"""

def create_dream_poem():
    """创作一首关于梦想的短诗"""
    
    poem_lines = [
        "当晨曦轻抚沉睡的窗棂，",
        "梦想的种子已在心田苏醒。",
        "哪怕黑夜曾试图掩盖星光，",
        "希望的光芒终将穿透云层。",
        "",
        "每一次跌倒都是成长的印记，",
        "每一滴汗水浇灌未来的花枝。",
        "相信自己，勇敢追逐，",
        "梦想就在前方，触手可及。",
        "",
        "让勇气化作翅膀，",
        "让信念成为风帆。",
        "在浩瀚星河中航行，",
        "梦想终将绽放璀璨光芒。"
    ]
    
    return "\n".join(poem_lines)


if __name__ == "__main__":
    poem = create_dream_poem()
    print("=" * 50)
    print("🌟 梦想诗篇 🌟")
    print("=" * 50)
    print(poem)
    print("=" * 50)
