#!/usr/bin/env python3
"""
爱情诗篇 - 关于爱情的短诗创作模块
情感真挚，语言优美
"""

def create_love_poem():
    """创作一首关于爱情的短诗"""
    
    poem = """爱情诗篇

在时光的河流里，你是唯一的岸
每一次回眸，都泛起温柔的涟漪
当世界喧嚣，你轻声说"我在"
便是我此生最安稳的港湾

你眼中有星辰闪烁，那是黎明前的光
我听见心跳的声音，与你的呼吸同频
无需言语，一个眼神就懂得
所有未曾说出口的爱意

岁月流转，容颜会老去
但这份爱如初春的花，永远鲜活
在每一个清晨与黄昏
我都在，你也在，便是永恒

"""
    return poem


def main():
    """主函数：输出爱情短诗"""
    poem = create_love_poem()
    print("=" * 50)
    print(poem)
    print("=" * 50)


if __name__ == "__main__":
    main()
