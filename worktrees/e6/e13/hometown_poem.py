#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
故乡诗篇 - 创作一首关于故乡的短诗，唤起乡愁情感
"""


def create_hometown_poem():
    """创作关于故乡的短诗"""
    poem_lines = [
        "故乡的月光",
        "",
        "那轮熟悉的月亮",
        "依旧挂在老屋的屋檐上",
        "照亮了青石板路",
        "也照亮了我远行的方向",
        "",
        "炊烟袅袅升起",
        "带着母亲的味道",
        "飘过漫长的岁月",
        "在梦里轻轻呼唤",
        "",
        "小桥流水人家",
        "燕子归来依旧",
        "只是故人不在",
        "只剩空巷回响",
        "",
        "乡愁是一枚小小的邮票",
        "寄托着无尽的思念",
        "穿越千山万水",
        "只为那一缕乡音",
        "",
        "无论走得多远",
        "故乡的月光",
        "永远是我心中的灯塔",
        "照亮归途"
    ]
    return "\n".join(poem_lines)


def main():
    """主函数"""
    poem = create_hometown_poem()
    print("=" * 40)
    print("故乡诗篇")
    print("=" * 40)
    print(poem)
    print("=" * 40)


if __name__ == "__main__":
    main()
