#!/usr/bin/env python3
"""
时光诗篇 - 时光流逝的短诗创作
"""

def create_poem():
    """创作关于时光流逝的短诗"""
    poem = """时光诗篇

沙漏倾泻，无声的河流
每一粒都是逝去的昨天
我们在倒影中辨认容颜
却找不到昨天的答案

时钟转动的每一秒
都是无法重来的瞬间
我们在追逐中渐行渐远
却在回望中看见起点

时光不是流逝的箭矢
而是轮回的圆环
我们以为在失去
实则是在成全

当晨曦再次照亮窗台
昨日的落叶已化作春泥
时光不曾带走什么
只是教会我们珍惜"""
    return poem

if __name__ == "__main__":
    print(create_poem())
