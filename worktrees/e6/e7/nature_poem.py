#!/usr/bin/env python3
"""
自然诗篇 - 创作一首关于自然的短诗
包含意象：风、树、河流
"""

def create_nature_poem():
    """创作并输出自然短诗"""
    
    poem = """自然诗篇

风，从远方来，
抚过古老的树梢，
树叶沙沙作响，
如低语，如歌唱。

树，静静伫立，
根须深扎泥土，
枝叶拥抱天空，
见证岁月的流转。

河流，蜿蜒流淌，
穿过山川，掠过田野，
带走时光的痕迹，
留下生命的歌谣。

风、树、河流，
在自然的怀抱中，
和谐共生，
生生不息。
"""
    
    print(poem)

if __name__ == "__main__":
    create_nature_poem()
